// Rebuilds src/data/popular.js from public download rankings.
//   node scripts/update-popular.mjs
//   EXCLUDE_NAMES='some-vendor' node scripts/update-popular.mjs   (optional filter)
// npm:  registry search API (includes weekly downloads), many keyword queries
// PyPI: hugovk/top-pypi-packages (monthly downloads, top 15k)
import { writeFileSync } from 'node:fs';

const NPM_LIMIT = 4000;
const PYPI_LIMIT = 5000;
const KEYWORDS = `react vue angular svelte next nuxt express koa fastify nest http server client api rest graphql
websocket socket cli command terminal color log logger debug test testing jest mocha vitest assert mock lint eslint
prettier format babel typescript types webpack rollup vite esbuild bundler plugin loader postcss css sass less style
styled tailwind ui component icons animation chart d3 three canvas svg image pdf markdown html dom parser xml json
yaml csv excel date time moment uuid crypto hash jwt auth oauth passport session cookie security password bcrypt
database sql mysql postgres sqlite mongo mongodb redis orm prisma sequelize typeorm knex cache queue job cron
aws azure google firebase cloud s3 docker kubernetes git github ci deploy env config dotenv path file fs glob
stream buffer zip compression archive download upload fetch request axios ajax promise async util utility lodash
string array object validation schema zod yup ajv form state redux store router i18n email mail sms stripe
payment ai openai llm chat bot discord slack telegram electron native mobile ios android expo browser chrome
puppeteer playwright selenium scrape crawl monorepo workspace build compile transpile polyfill shim es6 node
event emitter process child spawn shell os network dns proxy tcp ip url query encode decode base64 binary
semver version package npm install registry template engine mustache handlebars ejs pug minify uglify terser
source map coverage benchmark performance monitor metrics sentry error retry limit throttle debounce color
chalk spinner progress prompt inquirer argument args yargs commander table diff merge clone deep equal
immutable functional rxjs observable signal hooks context vuex pinia jquery bootstrap material antd`.split(/\s+/).filter(Boolean);

async function json(url) {
  for (let i = 0; i < 3; i++) {
    try {
      const r = await fetch(url, { headers: { 'user-agent': 'installguard-list-builder' } });
      if (r.ok) return r.json();
    } catch {}
    await new Promise((r) => setTimeout(r, 1000 * (i + 1)));
  }
  return null;
}

const npm = new Map();
for (const kw of KEYWORDS) {
  for (const from of [0, 250]) {
    const d = await json(`https://registry.npmjs.org/-/v1/search?text=${encodeURIComponent(kw)}&size=250&from=${from}`);
    for (const o of d?.objects || []) {
      const w = o.downloads?.weekly ?? 0;
      if (w > (npm.get(o.package.name) ?? 0)) npm.set(o.package.name, w);
    }
  }
}
// Optional: EXCLUDE_NAMES='regex' leaves matching names out of the lists.
const EXCLUDE = process.env.EXCLUDE_NAMES ? new RegExp(process.env.EXCLUDE_NAMES, 'i') : null;
const npmTop = [...npm].filter(([n, w]) => w >= 100_000 && !EXCLUDE?.test(n)).sort((a, b) => b[1] - a[1]).slice(0, NPM_LIMIT).map(([n]) => n.toLowerCase());

const py = await json('https://raw.githubusercontent.com/hugovk/top-pypi-packages/main/top-pypi-packages.min.json');
const pypiTop = (py?.rows || []).filter((r) => !EXCLUDE?.test(r.project)).slice(0, PYPI_LIMIT).map((r) => r.project.toLowerCase().replace(/[-_.]+/g, '-'));

if (npmTop.length < 1000 || pypiTop.length < 1000) {
  console.error(`refusing to write: only ${npmTop.length} npm / ${pypiTop.length} pypi names`);
  process.exit(1);
}

const fmt = (arr) => JSON.stringify([...new Set(arr)].sort()).replace(/","/g, '",\n"').replace('["', '[\n"').replace('"]', '",\n]');
writeFileSync(
  new URL('../src/data/popular.js', import.meta.url),
  `// Generated by scripts/update-popular.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.\n` +
    `// Most-downloaded package names. A new package whose name is one or two\n// keystrokes away from one of these is a classic typosquatting setup.\n\n` +
    `export const POPULAR_NPM = ${fmt(npmTop)};\n\nexport const POPULAR_PYPI = ${fmt(pypiTop)};\n`,
);
console.log(`npm: ${npmTop.length} names (min weekly ${npm.get(npmTop.at(-1))}), pypi: ${pypiTop.length}`);
